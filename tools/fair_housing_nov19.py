def forms(s):
    return (s, s.replace("'", "&#x27;"))

files = sorted(glob.glob('src/towns/*.html')) + sorted(glob.glob('src/data/*.json'))
text = {f: open(f).read() for f in files}
miss, hits = [], 0
for old, new in sorted(R, key=lambda p: -len(p[0])):
    n = 0
    for f in files:
        for o, nw in zip(forms(old), forms(new)):
            c = text[f].count(o)
            if c:
                text[f] = text[f].replace(o, nw); n += c
    if not n: miss.append(old)
    hits += n
if miss:
    print('NOT FOUND:'); [print(' ', m) for m in miss]; sys.exit(1)
ch = 0
for f in files:
    if text[f] != open(f).read():
        open(f, 'w').write(text[f]); ch += 1
print(len(R), 'rewrites,', hits, 'replacements,', ch, 'files changed')
